"""
Director Agent for Storyboard Multi-Agent Service.
Graph-Based Executive Showrunner built on Google ADK 2.0 Workflow.

Graph Architecture:
START -> plan_story_node -> review_story_node (HITL) -> director_parts_loop_node -> assemble_master_movie_node

1. plan_story_node: Real-time Google Search grounding + Writer story planning into state.
2. review_story_node: Formats screenplay overview and pauses at HITL gate via RequestInput.
3. director_parts_loop_node: Calls produce_single_part_node for Part 1..N sequentially in a loop.
4. assemble_master_movie_node: Assembles all completed Part master videos into final master movie.
"""
