def format_and_review_screenplay_tool(tool_context: Context) -> str:
    """
    Formats the storyboard script generated by WriterAgent into a clean,
    readable overview of all Parts, reference entities, and 6 sub-scenes each
    for human review before video rendering begins.
    """
    script = tool_context.state.get("storyboard_script", [])
    if not script:
        return "No screenplay found in state to review."

    topic = tool_context.state.get("story_topic", "Storyboard Movie")
    lines = [
        "\n" + "=" * 75,
        "  [STORYBOARD SCREENPLAY REVIEW - HUMAN-IN-THE-LOOP GATE]",
        "=" * 75,
        f"Topic: {topic}",
        f"Total Parts: {len(script)} (Total {len(script)*6} sub-scenes)\n"
    ]

    for p in script:
        p_num = p.get("part_number")
        title = p.get("title")
        synopsis = p.get("synopsis")
        queries = p.get("search_queries", [])
        lines.append(f"[PART {p_num}]: {title}")
        lines.append(f"   Synopsis: {synopsis}")
        lines.append(f"   Portraits to Search: {queries}")
        lines.append("   Sub-Scenes (3x2 Grid):")
        for s in p.get("subscenes", []):
            s_num = s.get("subscene_number")
            narration = s.get("narration", "")
            v_desc = s.get("visual_description", "")
            is_veo = s.get("is_veo_candidate", False)
            veo_tag = " [Veo 8s Motion Clip]" if is_veo else ""
            lines.append(f"     [{p_num}.{s_num}]{veo_tag} \"{narration[:70]}...\"")
            lines.append(f"            Visual: {v_desc[:80]}...")
        lines.append("-" * 75)

    review_str = "\n".join(lines)
    try:
        print(review_str)
    except UnicodeEncodeError:
        print(review_str.encode("ascii", errors="replace").decode("ascii"))
    return review_str


