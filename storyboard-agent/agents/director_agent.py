def plan_story_node(ctx: Context) -> str:
    """Node 1: Grounding & Screenplay Architecture."""
    if "storyboard_script" in ctx.state and ctx.state["storyboard_script"]:
        print("[DirectorWorkflow: Node 1] Using existing screenplay in state.")
        return "Screenplay already planned."

    topic = ctx.state.get("story_topic", "")
    if not topic and ctx.user_content and ctx.user_content.parts:
        for p in ctx.user_content.parts:
            text = getattr(p, "text", "")
            if text:
                topic = text.strip()
                import re
                m = re.search(r"on:\s*['\"](.*?)['\"]", topic)
                if m:
                    topic = m.group(1)
                ctx.state["story_topic"] = topic
                break
    num_parts = ctx.state.get("requested_parts", None)
    verbatim_mode = ctx.state.get("verbatim_mode", False)

    p_label = f"{num_parts}-Part" if num_parts else "Dynamic-Part"
    print(f"\n[DirectorWorkflow: Node 1] Planning {p_label} story for: '{topic}'...")

    # Research grounding if concise topic
    research_notes = ""
    if not verbatim_mode and len(topic.split()) < 30:
        print("[DirectorWorkflow] Performing Google Search grounding...")
        research_notes = google_search_grounding_tool(ctx, query=topic)

    if verbatim_mode:
        res = chunk_verbatim_story_parts_tool(ctx, source_text=topic, num_parts=num_parts)
    else:
        res = plan_creative_story_parts_tool(ctx, topic=topic, context_notes=research_notes, num_parts=num_parts)

    return res


def review_story_node(ctx: Context):
    """Node 2: Human-in-the-Loop Review Gate."""
    user_text = ""
    if ctx.user_content and ctx.user_content.parts:
        for p in ctx.user_content.parts:
            if getattr(p, "text", None):
                user_text += p.text.strip().lower()

    # Check if user already approved
    if ctx.state.get("approved") or "approve" in user_text or "yes" in user_text or user_text in ["y", "proceed"]:
        print("[DirectorWorkflow: Node 2] Human director approved screenplay! Proceeding to video production.")
        ctx.state["approved"] = True
        return "Screenplay approved by human"

    # Present formatted breakdown and pause execution
    format_and_review_screenplay_tool(ctx)
    print("[DirectorWorkflow: Node 2] Pausing for Human-in-the-Loop approval...")
    return RequestInput(message="Do you approve this screenplay to proceed with video generation?")


async def director_parts_loop_node(ctx: Context) -> str:
    """Node 3: Sequentially dispatches the PartProductionWorkflow graph for each Part in order."""
    script = ctx.state.get("storyboard_script", [])
    if not script:
        return "No approved script in state."

    print(f"\n[DirectorWorkflow: Node 3] Orchestrating {len(script)} Parts sequentially via PartProductionWorkflow...")
    completed_parts = []
    part_wf = create_part_production_workflow()

    for p in script:
        p_num = p.get("part_number")
        title = p.get("title", f"Part {p_num}")
        print(f"\n[DirectorWorkflow] Dispatching Part #{p_num}/{len(script)} ('{title}') to PartProductionWorkflow...")
        ctx.state["active_part_number"] = p_num
        res = await ctx.run_node(part_wf)
        info = json.loads(res) if isinstance(res, str) and res.startswith("{") else {}
        part_master = info.get("part_master_path") or res
        completed_parts.append(part_master)
        print(f"[DirectorWorkflow] Part #{p_num} successfully completed -> {part_master}")

    ctx.state["completed_part_videos"] = completed_parts
    return json.dumps({"status": "SUCCESS", "parts_produced": len(completed_parts)})


def assemble_master_movie_node(ctx: Context) -> str:
    """Node 4: Master Movie Assembly."""
    parts = ctx.state.get("completed_part_videos", [])
    print(f"\n[DirectorWorkflow: Node 4] Assembling final master movie from {len(parts)} Parts...")
    movie_res = concatenate_master_movie_tool(ctx, json.dumps(parts))
    info = json.loads(movie_res) if isinstance(movie_res, str) and movie_res.startswith("{") else {}
    if info.get("movie_path"):
        ctx.state["final_movie_path"] = info["movie_path"]
        ctx.state["master_movie_path"] = info["movie_path"]
    return movie_res


# ------------------------------------------------------------------------------
# 3. Graph Compilation
# ------------------------------------------------------------------------------

def create_director_workflow() -> Workflow:
    """
    Constructs the native ADK 2.0 Graph-Based Director Workflow.
    Edges:
    START -> plan_story_node -> review_story_node (HITL) -> director_parts_loop -> assemble_master_movie_node
    """
    director_parts_loop = FunctionNode(
        name="director_parts_loop",
        func=director_parts_loop_node,
        rerun_on_resume=True
    )

    return Workflow(
        name="director_workflow",
        description="ADK 2.0 Graph-Based Director Workflow",
        edges=[
            (START, plan_story_node, review_story_node, director_parts_loop, assemble_master_movie_node)
        ]
    )


def create_director_agent() -> Workflow:
    """Factory function for Director workflow."""
    return create_director_workflow()
